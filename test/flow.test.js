import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { DatabaseSync } from 'node:sqlite';

test('полный обмен, права и спор', async t => {
  const dir=fs.mkdtempSync(path.join(os.tmpdir(),'skillbarter-test-'));
  const port=31000+Math.floor(Math.random()*10000);
  process.env.PORT=String(port);
  process.env.SKILLBARTER_DATA_DIR=dir;
  const {server,db:serverDb}=await import('../server.js');
  t.after(async()=>{await new Promise(r=>server.close(r));serverDb.close();fs.rmSync(dir,{recursive:true,force:true});});
  const base=`http://127.0.0.1:${port}`;
  for(let i=0;i<80;i++){try{if((await fetch(base+'/api/bootstrap')).ok)break;}catch{}await new Promise(r=>setTimeout(r,80));}
  assert.equal((await fetch(base+'/')).status,200);
  const call=async (url,method='GET',body,cookie='')=>{const r=await fetch(base+'/api'+url,{method,headers:{'Content-Type':'application/json',Cookie:cookie},body:body?JSON.stringify(body):undefined});return {status:r.status,data:await r.json(),cookie:r.headers.get('set-cookie')?.split(';')[0]};};
  const a=await call('/auth/register','POST',{name:'Тест Заказчик',email:'customer@example.com',password:'Pass12345!'});
  const b=await call('/auth/register','POST',{name:'Тест Исполнитель',email:'provider@example.com',password:'Pass12345!'});
  const admin=await call('/auth/login','POST',{email:'admin@skillbarter.local',password:'Admin12345!'});
  assert.equal(a.status,200);assert.equal(b.status,200);assert.equal(admin.status,200);
  assert.equal(a.data.user.available,120);
  assert.equal((await call('/admin/dashboard','GET',null,a.cookie)).status,403);
  const initialAdmin=(await call('/admin/dashboard','GET',null,admin.cookie));
  assert.equal(initialAdmin.status,200);
  assert.ok(initialAdmin.data.users.some(u=>u.name==='Айару Кайрат'));
  assert.ok(initialAdmin.data.users.some(u=>u.name==='Кобеев Алмас'));
  const offer=await call('/offers','POST',{title:'Учимся вместе',description:'Подробное описание тестового занятия для обмена знаниями.',category_id:1,level:'Начинающий',language:'Русский',format:'Онлайн',min_minutes:30,max_minutes:120},b.cookie);
  assert.equal(offer.status,201,JSON.stringify(offer.data));
  const offerId=offer.data.id;
  assert.equal((await call('/offers/'+offerId)).status,200);
  const cardImage=await fetch(base+'/images/development.png');
  assert.equal(cardImage.status,200);
  assert.equal(cardImage.headers.get('content-type'),'image/png');
  const png='data:image/png;base64,iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAusB9WlLQWAAAAAASUVORK5CYII=';
  assert.equal((await call('/profile/avatar','POST',{image:'data:image/png;base64,not-an-image'},b.cookie)).status,400);
  const uploaded=await call('/profile/avatar','POST',{image:png},b.cookie);
  assert.equal(uploaded.status,200,JSON.stringify(uploaded.data));
  assert.equal((await call('/users/'+b.data.user.id)).data.user.avatar_file,uploaded.data.user.avatar_file);
  assert.equal((await fetch(base+uploaded.data.user.avatar_file)).status,200);
  assert.equal((await call('/offers/'+offerId,'PATCH',{active:false},a.cookie)).status,403);
  const starts=new Date(Date.now()+86400000).toISOString();
  assert.equal((await call('/requests','POST',{offer_id:offerId,minutes:60,starts_at:starts,format:'Онлайн'},b.cookie)).status,400);
  const request=await call('/requests','POST',{offer_id:offerId,minutes:60,starts_at:starts,format:'Онлайн'},a.cookie);
  assert.equal(request.status,201,JSON.stringify(request.data));
  const id=request.data.id;
  assert.equal((await call(`/requests/${id}/accept`,'POST',{},a.cookie)).status,400);
  assert.equal((await call(`/requests/${id}/messages`,'POST',{message:'Привет'},a.cookie)).status,403);
  assert.equal((await call(`/requests/${id}/accept`,'POST',{},b.cookie)).status,200);
  assert.equal((await call(`/requests/${id}/accept`,'POST',{},b.cookie)).status,400);
  let w=(await call('/wallet','GET',null,a.cookie)).data;
  assert.equal(w.available,60);assert.equal(w.reserved,60);
  assert.equal((await call(`/requests/${id}/messages`,'POST',{message:'Привет!'},a.cookie)).status,201);
  const db=new DatabaseSync(path.join(dir,'skillbarter.sqlite'));
  db.prepare("UPDATE requests SET starts_at=datetime('now','-2 hours') WHERE id=?").run(id);
  assert.equal((await call(`/requests/${id}/mark-done`,'POST',{},b.cookie)).status,200);
  assert.equal((await call(`/requests/${id}/confirm`,'POST',{},a.cookie)).status,200);
  assert.equal((await call(`/requests/${id}/confirm`,'POST',{},a.cookie)).status,400);
  w=(await call('/wallet','GET',null,a.cookie)).data;
  assert.equal(w.available,60);assert.equal(w.reserved,0);
  assert.equal((await call('/wallet','GET',null,b.cookie)).data.available,180);
  assert.equal((await call(`/requests/${id}/reviews`,'POST',{rating:5,body:'Отличная встреча!'},a.cookie)).status,201);
  assert.equal((await call(`/requests/${id}/reviews`,'POST',{rating:5,body:'Отличная встреча!'},a.cookie)).status,409);
  const second=await call('/requests','POST',{offer_id:offerId,minutes:30,starts_at:new Date(Date.now()+172800000).toISOString(),format:'Онлайн'},a.cookie);
  assert.equal(second.status,201);
  assert.equal((await call(`/requests/${second.data.id}/accept`,'POST',{},b.cookie)).status,200);
  db.prepare("UPDATE requests SET starts_at=datetime('now','-1 hour') WHERE id=?").run(second.data.id);
  assert.equal((await call(`/requests/${second.data.id}/dispute`,'POST',{reason:'Не было занятия',description:'Исполнитель не пришёл на назначенную встречу.'},a.cookie)).status,200);
  const before=(await call('/wallet','GET',null,a.cookie)).data;
  assert.equal(before.reserved,30);
  const dash=(await call('/admin/dashboard','GET',null,admin.cookie)).data;
  const dispute=dash.disputes.find(x=>x.request_id===second.data.id);
  assert.ok(dispute);
  assert.equal((await call(`/admin/disputes/${dispute.id}/resolve`,'POST',{resolution:'refund',note:'Услуга не оказана'},admin.cookie)).status,200);
  assert.equal((await call(`/admin/disputes/${dispute.id}/resolve`,'POST',{resolution:'refund',note:'Повтор'},admin.cookie)).status,409);
  const after=(await call('/wallet','GET',null,a.cookie)).data;
  assert.equal(after.available,60);assert.equal(after.reserved,0);
  assert.equal((await call('/admin/users','POST',{name:'Чужой админ',email:'bad@example.com',password:'Pass12345!',role:'admin'},b.cookie)).status,403);
  const created=await call('/admin/users','POST',{name:'Новый модератор',email:'moderator@example.com',password:'Pass12345!',role:'admin'},admin.cookie);
  assert.equal(created.status,201);
  const moderator=await call('/auth/login','POST',{email:'moderator@example.com',password:'Pass12345!'});
  assert.equal(moderator.status,200);
  assert.equal((await call('/admin/dashboard','GET',null,moderator.cookie)).status,200);
  assert.equal((await call(`/admin/users/${moderator.data.user.id}/role`,'PATCH',{role:'user',note:'Попытка снять свою роль'},moderator.cookie)).status,403);
  const normal=await call('/admin/users','POST',{name:'Будущий админ',email:'future@example.com',password:'Pass12345!',role:'user'},admin.cookie);
  assert.equal(normal.status,201);
  const normalLogin=await call('/auth/login','POST',{email:'future@example.com',password:'Pass12345!'});
  assert.equal(normalLogin.status,200);
  assert.equal((await call(`/admin/users/${normal.data.id}/role`,'PATCH',{role:'admin',note:'Назначение модератором'},admin.cookie)).status,200);
  assert.equal((await call('/admin/dashboard','GET',null,normalLogin.cookie)).status,401);
  const promoted=await call('/auth/login','POST',{email:'future@example.com',password:'Pass12345!'});
  assert.equal((await call('/admin/dashboard','GET',null,promoted.cookie)).status,200);
  db.close();
});
